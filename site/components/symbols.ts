function milan(): Sym {
  // Миланский собор: фасад-щипец, порталы и шпили, Мадоннина на центральном
  let d = "M60 360H640M80 360V170L350 70L620 170V360";
  for (let i = 0; i < 5; i++) {
    const big = i === 2;
    d += arch(118 + i * 100 - (big ? 10 : 0), big ? 70 : 50, 360, big ? 236 : 268);
  }
  const sp: [number, number, number][] = [
    [80, 170, 60], [140, 148, 70], [210, 122, 80], [280, 96, 90], [350, 70, 140],
    [420, 96, 90], [490, 122, 80], [560, 148, 70], [620, 170, 60],
  ];
  for (const [x, y, h] of sp) d += `M${x - 6} ${y}V${y - h + 14}L${x} ${y - h}L${x + 6} ${y - h + 14}V${y}`;
  d += "M350 -70V-92M343 -80H357";
  return { viewBox: "50 -100 600 470", d };
}

function lyon(): Sym {
  // Базилика Фурвьер: корпус, четыре восьмигранные башни, фронтон с портиком
  let d = "M40 330H760M120 330V150H680V330";
  const towers = [60, 220, 520, 680];
  for (const x of towers) {
    d += `M${x} 330V70H${x + 60}V330`;
    for (let k = 0; k < 4; k++) d += `M${x + k * 15} 70V56H${x + k * 15 + 8}V70`;
    d += `M${x + 18} 140V110H${x + 42}V140`;
  }
  d += "M300 150L400 92L500 150";
  for (let i = 0; i < 6; i++) d += `M${300 + i * 40} 330V196`;
  d += "M290 196H510";
  d += arch(370, 60, 330, 236);
  d += "M400 92V60M392 70H408";
  return { viewBox: "30 40 740 300", d };
}

function naples(): Sym {
  // Везувий с двумя вершинами, неаполитанская пиния и линия залива
  let d = "M0 300C120 296 210 250 300 180C340 150 360 120 400 112C430 106 446 122 470 118C500 112 520 96 548 104C600 120 660 200 720 250C780 290 840 298 900 300";
  d += "M380 116C392 90 400 70 396 40M404 112C420 86 440 70 470 60";
  d += "M760 300V170M760 210C740 190 720 186 700 190M760 196C786 176 808 174 826 180";
  d += "M640 170C650 140 700 126 740 132C760 112 810 112 840 132C880 128 912 146 902 166C880 180 820 178 790 172C760 182 700 184 660 178C646 176 638 174 640 170Z";
  for (let k = 0; k < 2; k++) {
    let w = `M${40 + k * 50} ${330 + k * 18}`;
    for (let x = 0; x < 18; x++) w += "q20 -7 40 0";
    d += w;
  }
  return { viewBox: "0 20 920 350", d };
}

const SYMBOLS: Record<CitySymbol, () => Sym> = { verona, rimini, venice, florence, milan, lyon, naples };

export function citySymbol(slug: string): Sym | null {
  const f = SYMBOLS[slug as CitySymbol];
  return f ? f() : null;
}
