export const categoryPath = (c: CategoryPage) => `/catalog/${c.slug}`;

export function categoryBySlug(slug: string) {
  return categoryPages.find((c) => c.slug === slug);
}

export function categoryByPath(pathname: string) {
  const m = /^\/catalog\/([^/]+)\/?$/.exec(pathname);
  return m ? categoryBySlug(m[1]) : undefined;
}

// страница, которой соответствует набор фильтров (только один из kat / nazn / tkan)
export function categoryFor(f: { kat: CategoryId | null; nazn: PurposeId | null; tkan: Tkan | null }) {
  return categoryPages.find(
    (c) =>
      (c.preset.kat ?? null) === f.kat &&
      (c.preset.nazn ?? null) === f.nazn &&
      (c.preset.tkan ?? null) === f.tkan,
  );
}

export function categoryForPurpose(id: PurposeId) {
  return categoryPages.find((c) => c.preset.nazn === id && !c.preset.kat && !c.preset.tkan);
}
export function categoryForKat(id: CategoryId) {
  return categoryPages.find((c) => c.preset.kat === id && !c.preset.nazn && !c.preset.tkan);
}

