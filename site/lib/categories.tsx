// ссылки меню и первого экрана: на страницу категории, а где её нет — на ближайшую по смыслу
const katToPurpose: Partial<Record<CategoryId, PurposeId>> = {
  kitchen: "kuhnya",
  mats: "kovriki",
  robes: "halaty",
  sets: "podarki",
  hotel: "oteli",
};
export function purposeHref(id: PurposeId) {
  const c = categoryForPurpose(id);
  return c ? categoryPath(c) : `/catalog?nazn=${id}`;
}
export function catHref(id: CategoryId) {
  const c = categoryForKat(id);
  if (c) return categoryPath(c);
  const p = katToPurpose[id];
  return p ? purposeHref(p) : `/catalog?kat=${id}`;
}

// раздел товара для хлебных крошек
export function productCategory(p: { name: string; category: CategoryId }) {
  if (/вафел/i.test(p.name)) return categoryBySlug("vafelnye-polotenca");
  return catHref(p.category).startsWith("/catalog/")
    ? categoryByPath(catHref(p.category))
    : undefined;
}
